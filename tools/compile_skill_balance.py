"""Validate gameplay balance and compile a deterministic, dependency-free C++ table."""
from pathlib import Path
import json
import sys

FIELDS = {
    'schema', 'ticks_per_day', 'work_units_per_tick', 'gather_base_work_ticks',
    'build_base_work_ticks', 'work_units_per_xp', 'skill_cap_bp', 'familiarity_cap_bp',
    'familiarity_grace_days', 'familiarity_decay_days',
    'familiarity_recovery_day_numerator', 'familiarity_recovery_day_denominator', 'experience_curve',
}

def validated(raw):
    if not isinstance(raw, dict) or set(raw) != FIELDS:
        raise ValueError('Skill balance has missing or unknown fields')
    for key in FIELDS - {'experience_curve'}:
        if type(raw[key]) is not int or not 1 <= raw[key] <= 1_000_000:
            raise ValueError(f'Invalid positive integer: {key}')
    if raw['schema'] != 1 or raw['skill_cap_bp'] != 1500 or raw['familiarity_cap_bp'] > 200:
        raise ValueError('Skill balance violates the author cap')
    if raw['ticks_per_day'] != 1200:
        raise ValueError('Skill day must match the simulation calendar')
    curve = raw['experience_curve']
    if not isinstance(curve, list) or not 2 <= len(curve) <= 32:
        raise ValueError('Invalid XP curve size')
    previous_x, previous_y = -1, -1501
    for point in curve:
        if not isinstance(point, list) or len(point) != 2 or any(type(n) is not int for n in point):
            raise ValueError('Invalid XP curve point')
        x, y = point
        if not previous_x < x <= 1_000_000_000 or not previous_y <= y <= 1500 or y < -1500:
            raise ValueError('XP curve must have increasing XP and nondecreasing bounded effects')
        previous_x, previous_y = point
    if curve[0][0] != 0:
        raise ValueError('XP curve must start at zero')
    numerator = raw['ticks_per_day'] * raw['work_units_per_tick'] * raw['familiarity_recovery_day_numerator']
    denominator = raw['familiarity_recovery_day_denominator']
    if numerator % denominator or not 1 <= numerator // denominator <= 1_000_000_000:
        raise ValueError('Recovery must be an exact bounded work-unit count')
    if raw['work_units_per_tick'] * max(raw['gather_base_work_ticks'], raw['build_base_work_ticks']) > 1_000_000_000:
        raise ValueError('Useful work credit overflow')
    if raw['ticks_per_day'] * max(raw['familiarity_grace_days'], raw['familiarity_decay_days']) > 1_000_000_000:
        raise ValueError('Familiarity duration overflow')
    return raw

def header(data):
    data = validated(data)
    canonical = json.dumps(data, sort_keys=True, separators=(',', ':'), ensure_ascii=True)
    lines = ['// Generated by compile_skill_balance.py; edit data/skills.json.', '#pragma once',
             '#include <array>', '#include <cstdint>', '#include <string_view>',
             'namespace ribterra::skill_balance {']
    for key in sorted(FIELDS - {'experience_curve'}):
        lines.append(f'inline constexpr std::uint32_t {key} = {data[key]};')
    points = ','.join('{{{},{}}}'.format(x,y) for x,y in data['experience_curve'])
    lines.append(f'inline constexpr std::array<std::array<int,2>,{len(data["experience_curve"])}> experience_curve {{{{{points}}}}};')
    lines.append('inline constexpr std::string_view canonical_json = R"balance(' + canonical + ')balance";')
    lines.append('} // namespace ribterra::skill_balance\n')
    return '\n'.join(lines)

if __name__ == '__main__':
    source, destination = map(Path, sys.argv[1:])
    rendered = header(json.loads(source.read_text(encoding='utf-8')))
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_text(encoding='utf-8') != rendered:
        destination.write_text(rendered, encoding='utf-8', newline='\n')
